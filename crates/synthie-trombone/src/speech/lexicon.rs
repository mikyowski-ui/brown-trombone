/// Find `word` in a sorted list of `word code` lines.
fn find<'a>(data: &'a str, word: &str) -> Option<&'a str> {
    let bytes = data.as_bytes();
    let (mut lo, mut hi) = (0, bytes.len());
    while lo < hi {
        let mid = lo + (hi - lo) / 2;
        // The line holding `mid`.
        let start = bytes[..mid].iter().rposition(|&b| b == b'\n').map_or(0, |k| k + 1);
        let end = bytes[mid..].iter().position(|&b| b == b'\n').map_or(bytes.len(), |k| mid + k);
        let line = &data[start..end];
        let (key, code) = line.split_once(' ').unwrap_or((line, ""));
        match key.cmp(word) {
            core::cmp::Ordering::Equal => return Some(code),
            core::cmp::Ordering::Less => lo = end + 1,
            core::cmp::Ordering::Greater => hi = start,
        }
    }
    None
}

/// The sounds a dictionary code stands for.
fn decode(code: &str) -> Pron {
    let mut out = Pron::new();
    let mut accent = false;
    for b in code.bytes() {
        if b == b'\'' {
            accent = true;
        } else if let Some(&(_, p)) = CODES.iter().find(|(c, _)| *c == b) {
            out.push((p, accent));
            accent = false;
        }
    }
    out
}

/// The built-in dictionary entry for `word`.
pub(super) fn builtin(word: &str) -> Option<Pron> {
    find(CORE, word).or_else(|| find(EXTRA, word)).map(decode)
}

/// Sounds from ARPAbet text (`K AX N UW1`), `1` marking the accent.
pub(super) fn parse_arpabet(s: &str) -> Pron {
    s.split_whitespace()
        .filter_map(|sym| Phoneme::from_symbol(sym).map(|p| (p, sym.ends_with('1'))))
        .collect()
}

// ===== words ===============================================================

/// The sounds of one word (lower case, apostrophes allowed).
pub(super) fn pronounce(word: &str, lex: Lexicon) -> Pron {
    if let Some(p) = lex(word) {
        return p;
    }
    // Possessives and contractions.
    for (end, sounds) in [
        ("n't", &[P::Ax, P::N, P::T][..]),
        ("'ll", &[P::L][..]),
        ("'ve", &[P::V][..]),
        ("'re", &[P::Er][..]),
        ("'d", &[P::D][..]),
        ("'m", &[P::M][..]),
    ] {
        if let Some(stem) = word.strip_suffix(end).filter(|s| !s.is_empty()) {
            let mut p = pronounce(stem, lex);
            p.extend(sounds.iter().map(|&s| (s, false)));
            return p;
        }
    }
    if let Some(stem) = word.strip_suffix("'s").or_else(|| word.strip_suffix("s'")).filter(|s| !s.is_empty()) {
        return add_s(pronounce(stem, lex));
    }
    let letters: String = word.chars().filter(char::is_ascii_lowercase).collect();
    if letters.is_empty() {
        return Pron::new();
    }
    if letters.len() != word.len() {
        if let Some(p) = lex(&letters) {
            return p;
        }
    }
    analyse(&letters, lex, 0)
}

/// A word known to the dictionary, or built from known parts.
fn known(w: &str, lex: Lexicon, depth: u8) -> Option<Pron> {
    lex(w).or_else(|| if depth < 3 { from_known(w, lex, depth + 1) } else { None })
}

/// Pronounce letters: the dictionary, known parts, regular endings, rules.
fn analyse(w: &str, lex: Lexicon, depth: u8) -> Pron {
    analyse_as(w, lex, depth, false)
}

/// [`analyse`], `verb` if the word had a verb ending.
fn analyse_as(w: &str, lex: Lexicon, depth: u8, verb: bool) -> Pron {
    if let Some(p) = lex(w) {
        return p;
    }
    if depth < 3 {
        if let Some(p) = from_known(w, lex, depth + 1) {
            return p;
        }
        if let Some(p) = inflected(w, lex, depth + 1, verb) {
            return p;
        }
    }
    rules::spell(w.as_bytes(), verb)
}

fn has_vowel(s: &str) -> bool {
    s.bytes().any(|c| matches!(c, b'a' | b'e' | b'i' | b'o' | b'u' | b'y'))
}

fn is_vowel(c: u8) -> bool {
    matches!(c, b'a' | b'e' | b'i' | b'o' | b'u')
}

/// Plural or third person `-s`: s after a voiceless sound, iz after a
/// hissing one, z otherwise.
fn add_s(mut p: Pron) -> Pron {
    match p.last().map(|&(q, _)| q) {
        Some(P::S | P::Z | P::Sh | P::Zh | P::Ch | P::Jh) => p.extend([(P::Ih, false), (P::Z, false)]),
        Some(P::P | P::T | P::K | P::F | P::Th) => p.push((P::S, false)),
        Some(_) => p.push((P::Z, false)),
        None => {}
    }
    p
}

/// Past `-ed`: id after t or d, t after a voiceless sound, d otherwise.
fn add_ed(mut p: Pron) -> Pron {
    match p.last().map(|&(q, _)| q) {
        Some(P::T | P::D) => p.extend([(P::Ih, false), (P::D, false)]),
        Some(P::P | P::K | P::F | P::Th | P::S | P::Sh | P::Ch) => p.push((P::T, false)),
        Some(_) => p.push((P::D, false)),
        None => {}
    }
    p
}

fn append(mut p: Pron, tail: &[Phoneme]) -> Pron {
    for &q in tail {
        // One sound where stem and ending meet on the same consonant.
        if p.last().is_some_and(|&(r, _)| r == q && !matches!(q.manner(), crate::phoneme::Manner::Vowel | crate::phoneme::Manner::Diphthong)) {
            continue;
        }
        p.push((q, false));
    }
    p
}

/// Prepend an unaccented prefix's sounds.
fn prepend(head: &[Phoneme], p: Pron) -> Pron {
    let mut out: Pron = head.iter().map(|&q| (q, false)).collect();
    for (q, s) in p {
        if !s && out.last().is_some_and(|&(r, _)| r == q) && !matches!(q.manner(), crate::phoneme::Manner::Vowel | crate::phoneme::Manner::Diphthong) {
            continue;
        }
        out.push((q, s));
    }
    out
}

/// Stems a suffix may have been added to: as written, with a doubled
/// consonant undone (`running`), with a dropped `e` restored (`making`),
/// with `i` back to `y` (`carried`).
fn stems(stem: &str) -> Vec<String> {
    let b = stem.as_bytes();
    let mut out = Vec::new();
    let n = b.len();
    if n >= 2 && b[n - 1] == b'i' {
        let mut s = String::from(&stem[..n - 1]);
        s.push('y');
        out.push(s);
    }
    out.push(String::from(stem));
    if n >= 3 && b[n - 1] == b[n - 2] && !is_vowel(b[n - 1]) {
        out.push(String::from(&stem[..n - 1]));
    }
    let mut e = String::from(stem);
    e.push('e');
    out.push(e);
    out
}

/// Whether a stem that lost a final `e` before `-ed` or `-ing` should get it
/// back: `hop` + `ed` was `hope` unless the consonant was doubled.
fn restore_e(stem: &str) -> bool {
    let b = stem.as_bytes();
    let n = b.len();
    if n < 2 {
        return false;
    }
    let last = b[n - 1];
    let prev = b[n - 2];
    // c and g are soft before the ending: danced, changed, judged.
    if last == b'c' || last == b'z' && is_vowel(prev) {
        return true;
    }
    // couple, settle, struggle.
    if last == b'l' && !is_vowel(prev) && prev != b'l' && prev != b'r' {
        return true;
    }
    if last == b'v' {
        return true;
    }
    if last == b'g' && matches!(prev, b'r' | b'd' | b'a') {
        return true;
    }
    if last == b'g' && prev == b'n' && n >= 3 && matches!(b[n - 3], b'a' | b'e') && !stem.ends_with("ong") {
        return stem.ends_with("ang") && n > 4 || stem.ends_with("eng");
    }
    if matches!(last, b's' | b'z') && matches!(prev, b'r' | b'n' | b'l' | b'p') && !stem.ends_with("ps") {
        return last == b's' && matches!(prev, b'r' | b'n' | b'l');
    }
    if last == b'h' && stem.ends_with("th") {
        // bathed, clothed, breathed.
        return n >= 3 && (b[n - 3] == b'a' || b[n - 3] == b'o' || stem.ends_with("eath") || stem.ends_with("ooth"));
    }
    if !is_vowel(prev) || is_vowel(last) || matches!(last, b'w' | b'x' | b'y' | b'h') {
        return false;
    }
    // A single vowel letter before the consonant.
    if n >= 3 && is_vowel(b[n - 3]) {
        return last == b's' && (stem.ends_with("aus") || stem.ends_with("ois") || stem.ends_with("eas") || stem.ends_with("ais") || stem.ends_with("ous") && n == 4 || stem.ends_with("uis"));
    }
    let syllables = stem.bytes().enumerate().filter(|&(k, c)| is_vowel(c) && (k == 0 || !is_vowel(b[k - 1]))).count();
    if syllables <= 1 {
        return !(prev == b'e' && matches!(last, b't' | b'n' | b'l' | b'd' | b'r' | b'k'));
    }
    let tail = &stem[n - 2..];
    match tail {
        "at" | "iz" | "is" | "ut" | "ud" | "uc" | "ur" | "ir" | "ar" | "ag" | "ib" | "ub" | "um" | "ul" | "uv" | "ov" | "ot" | "ap" | "ad" | "id" | "od" | "ak" | "ok" | "ik" | "uk" | "as" | "us" | "os" => {
            !(tail == "us" && !stem.ends_with("fus") && !stem.ends_with("cus") || tail == "us" && stem.ends_with("ocus") || tail == "id" && stem.ends_with("rid"))
        }
        "in" => !(stem.ends_with("min") || stem.ends_with("gin") || stem.ends_with("lin") || stem.ends_with("rin") && !stem.ends_with("frin")),
        "or" => matches!(b[n - 3], b'n' | b'l' | b't') && n >= 4 && !is_vowel(b[n - 4]) || stem.ends_with("nor"),
        "et" => matches!(b[n - 3], b'l' | b'p'),
        "it" => syllables == 2 && matches!(b[n - 3], b'c' | b'v' | b'n') && (stem.starts_with("in") || stem.starts_with("ex") || stem.starts_with("un") || stem.starts_with("ig") || stem.starts_with("re")),
        "ip" | "op" | "ep" | "er" | "en" | "on" | "an" | "el" | "al" | "ol" | "il" | "om" | "em" | "im" | "am" | "ab" | "eb" | "ob" | "ed" | "es" | "ek" | "ac" | "ec" | "ic" | "oc" | "eg" | "ig" | "og" | "ug" | "ev" | "av" | "iv" | "ez" | "az" | "oz" | "uz" => {
            matches!(tail, "iv" | "av" | "ev") || (tail == "il" && stem.ends_with("mil") && n == 4)
        }
        _ => false,
    }
}

/// Endings that can be added to any stem, pronounced from the stem.
///
/// `verb` marks a stem that already lost `-ed` or `-ing`, which is not
/// taken apart again (`embedding` is `embed`, not `emb`).
fn inflected(w: &str, lex: Lexicon, depth: u8, verb: bool) -> Option<Pron> {
    let b = w.as_bytes();
    let n = b.len();
    if verb {
        return None;
    }
    // -s, -es, -ies.
    let ys = w.ends_with("ys") && n >= 3 && !is_vowel(b[n - 3]);
    if n >= 4 && w.ends_with('s') && !w.ends_with("ss") && !w.ends_with("us") && !w.ends_with("is") && !ys && !w.ends_with("ous") {
        let base = &w[..n - 1];
        let sib = w.ends_with("ches") || w.ends_with("shes") || w.ends_with("sses") || w.ends_with("xes") || w.ends_with("zzes") || w.ends_with("ses") && n >= 5 && !is_vowel(b[n - 4]) && b[n - 4] != b'r' && b[n - 4] != b'n' && b[n - 4] != b'l' || w.ends_with("zes") && b[n - 4] == b'z';
        if w.ends_with("ies") && n >= 5 {
            let mut y = String::from(&w[..n - 3]);
            y.push('y');
            if has_vowel(&w[..n - 3]) {
                return Some(add_s(analyse(&y, lex, depth)));
            }
        } else if sib {
            let stem = &w[..n - 2];
            return Some(add_s(analyse(stem, lex, depth)));
        } else if w.ends_with("oes") && n >= 5 && !w.ends_with("shoes") {
            return Some(add_s(analyse(&w[..n - 2], lex, depth)));
        } else if has_vowel(&base[..base.len() - 1]) && (base.len() >= 3) && !(base.ends_with('a') && base.len() < 4) && !base.ends_with('u') && !base.ends_with('i') {
            return Some(add_s(analyse(base, lex, depth)));
        }
    }
    // -ed.
    if n >= 4 && w.ends_with("ed") && !w.ends_with("eed") {
        let stem = &w[..n - 2];
        let cluster_r = stem.len() >= 2 && stem.ends_with('r') && !is_vowel(stem.as_bytes()[stem.len() - 2]);
        if has_vowel(stem) && stem.len() >= 2 && !stem.ends_with('e') && !cluster_r {
            return Some(add_ed(stem_sound(stem, lex, depth)));
        }
        if stem.ends_with("ue") || stem.ends_with("ye") || stem.ends_with("oe") {
            return Some(add_ed(analyse(stem, lex, depth)));
        }
    }
    // -ing.
    if n >= 5 && w.ends_with("ing") {
        let stem = &w[..n - 3];
        if has_vowel(stem) && stem.len() >= 2 && !stem.ends_with('y') || stem.ends_with('y') && stem.len() >= 3 && has_vowel(&stem[..stem.len() - 1]) {
            let mut p = stem_sound(stem, lex, depth);
            // e of agreeing, i of skiing: the y glide is not added.
            p.push((P::Ih, false));
            p.push((P::Ng, false));
            return Some(p);
        }
    }
    // -ly.
    if n >= 5 && w.ends_with("ly") {
        let stem = &w[..n - 2];
        if let Some(s) = stem.strip_suffix("ical") {
            let p = analyse(&{
                let mut t = String::from(s);
                t.push_str("ic");
                t
            }, lex, depth);
            return Some(append(p, &[P::L, P::Iy]));
        }
        if w.ends_with("bly") || w.ends_with("mply") || w.ends_with("tly") && w.ends_with("ntly") && false {
            let mut le = String::from(&w[..n - 1]);
            le.push('e');
            let mut p = analyse(&le, lex, depth);
            if p.len() >= 2 && p[p.len() - 2].0 == P::Ax && p[p.len() - 1].0 == P::L {
                p.remove(p.len() - 2);
            }
            p.push((P::Iy, false));
            return Some(p);
        }
        if w.ends_with("ily") && n >= 6 && n - 3 >= 4 {
            let mut y = String::from(&w[..n - 3]);
            y.push('y');
            return Some(append(analyse(&y, lex, depth), &[P::L, P::Iy]));
        }
        let ok = stem.len() >= 4
            && has_vowel(stem)
            && (stem.ends_with('e') || !is_vowel(*stem.as_bytes().last().unwrap_or(&b'a')))
            && !stem.ends_with("pp")
            && !stem.ends_with("ppl")
            && !w.ends_with("ply")
            && !w.ends_with("gly");
        if ok {
            return Some(append(analyse(stem, lex, depth), &[P::L, P::Iy]));
        }
    }
    // -ness, -less, -ful, -ment.
    for (end, tail) in [
        ("ness", &[P::N, P::Ax, P::S][..]),
        ("less", &[P::L, P::Ax, P::S][..]),
        ("fully", &[P::F, P::Ax, P::L, P::Iy][..]),
        ("ful", &[P::F, P::Ax, P::L][..]),
        ("ments", &[P::M, P::Ax, P::N, P::T, P::S][..]),
        ("ment", &[P::M, P::Ax, P::N, P::T][..]),
        ("some", &[P::S, P::Ax, P::M][..]),
    ] {
        let Some(stem) = w.strip_suffix(end) else { continue };
        if stem.len() < 3 || !has_vowel(stem) {
            continue;
        }
        if end.starts_with("ment") && !(stem.ends_with('e') && stem.len() >= 4 && !stem.ends_with("ple") && !stem.ends_with("ele")) {
            continue;
        }
        let stem = if stem.ends_with('i') && end != "ment" && end != "ments" {
            let mut y = String::from(&stem[..stem.len() - 1]);
            y.push('y');
            y
        } else {
            String::from(stem)
        };
        return Some(append(analyse(&stem, lex, depth), tail));
    }
    // Compounds whose second part is a common word: henhouse, notebook.
    for second in SECOND {
        let Some(first) = w.strip_suffix(second) else { continue };
        if (first.len() >= 3 || matches!(first, "on" | "in" | "up" | "by")) && has_vowel(first) {
            let head = analyse(first, lex, depth);
            let mut tail = analyse(second, lex, depth);
            for t in &mut tail {
                t.1 = false;
            }
            let mut p = head;
            for t in tail {
                if p.last().is_some_and(|&(r, _)| r == t.0 && !matches!(t.0.manner(), crate::phoneme::Manner::Vowel | crate::phoneme::Manner::Diphthong)) {
                    continue;
                }
                p.push(t);
            }
            return Some(p);
        }
    }
    None
}

