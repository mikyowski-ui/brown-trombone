//! Words: the built-in pronouncing dictionary, and endings, prefixes and
//! compounds taken apart so that a known stem helps the words built on it.
//!
//! The dictionary holds the words the spelling rules get wrong: irregular
//! ones (`one`, `said`, `women`), and frequent ones whose accent or vowels
//! the rules cannot guess (`canoe`, `juice`). It is two sorted lists, one
//! word per line followed by a space and its sounds, one character each
//! (see [`CODES`]), with `'` before the accented vowel; a word with no `'`
//! is an unaccented function word.
//!
//! * `core.dict` (always built in) holds the hand-written entries of
//!   `manual.txt` and the most frequent irregular words.
//! * `extra.dict` (cargo feature `dictionary`, on by default) holds a few
//!   thousand less frequent ones.
//!
//! Both are generated by `examples/lexicon.rs` from `manual.txt` and the
//! CMU Pronouncing Dictionary (BSD licence, see `CMUDICT-LICENSE`).

use super::rules;
use crate::phoneme::Phoneme;
use alloc::string::String;
use alloc::vec::Vec;
use Phoneme as P;

/// Sounds of a word, each with whether it carries the accent.
pub(super) type Pron = Vec<(Phoneme, bool)>;

/// Where words are looked up before the rules are tried.
pub(super) type Lexicon<'a> = &'a dyn Fn(&str) -> Option<Pron>;

const CORE: &str = include_str!("core.dict");
#[cfg(feature = "dictionary")]
const EXTRA: &str = include_str!("extra.dict");
#[cfg(not(feature = "dictionary"))]
const EXTRA: &str = "";

