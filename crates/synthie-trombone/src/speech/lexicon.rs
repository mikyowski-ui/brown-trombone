/// A stem before `-ed` or `-ing`, with a dropped `e` or a doubled consonant
/// taken into account.
fn stem_sound(stem: &str, lex: Lexicon, depth: u8) -> Pron {
    for s in stems(stem) {
        if let Some(p) = known(&s, lex, depth) {
            return p;
        }
    }
    let b = stem.as_bytes();
    let n = b.len();
    if n >= 3 && b[n - 1] == b[n - 2] && !is_vowel(b[n - 1]) && !matches!(b[n - 1], b'l' | b's' | b'f' | b'z') {
        return analyse_as(&stem[..n - 1], lex, depth, true);
    }
    if n >= 3 && b[n - 1] == b'i' {
        let mut y = String::from(&stem[..n - 1]);
        y.push('y');
        return analyse(&y, lex, depth);
    }
    if restore_e(stem) {
        let mut e = String::from(stem);
        e.push('e');
        return analyse_as(&e, lex, depth, true);
    }
    analyse_as(stem, lex, depth, true)
}

/// Words built from a known stem: `-er`, `-y`, `-able`, prefixes, compounds
/// of two known words.
fn from_known(w: &str, lex: Lexicon, depth: u8) -> Option<Pron> {
    let n = w.len();
    // Suffixes on a known stem.
    for (end, tail) in [
        ("ers", &[P::Er, P::Z][..]),
        ("er", &[P::Er][..]),
        ("est", &[P::Ax, P::S, P::T][..]),
        ("ably", &[P::Ax, P::B, P::L, P::Iy][..]),
        ("able", &[P::Ax, P::B, P::Ax, P::L][..]),
        ("ism", &[P::Ih, P::Z, P::Ax, P::M][..]),
        ("ists", &[P::Ih, P::S, P::T, P::S][..]),
        ("ist", &[P::Ih, P::S, P::T][..]),
        ("ish", &[P::Ih, P::Sh][..]),
        ("ship", &[P::Sh, P::Ih, P::P][..]),
        ("hood", &[P::Hh, P::Uh, P::D][..]),
        ("dom", &[P::D, P::Ax, P::M][..]),
        ("ness", &[P::N, P::Ax, P::S][..]),
        ("less", &[P::L, P::Ax, P::S][..]),
        ("ful", &[P::F, P::Ax, P::L][..]),
        ("ment", &[P::M, P::Ax, P::N, P::T][..]),
        ("ments", &[P::M, P::Ax, P::N, P::T, P::S][..]),
        ("ly", &[P::L, P::Iy][..]),
        ("y", &[P::Iy][..]),
        ("s", &[][..]),
        ("es", &[][..]),
        ("ed", &[][..]),
        ("d", &[][..]),
        ("ing", &[P::Ih, P::Ng][..]),
    ] {
        let Some(stem) = w.strip_suffix(end) else { continue };
        if stem.len() < 2 || !has_vowel(stem) {
            continue;
        }
        for s in stems(stem) {
            if s.len() < 2 {
                continue;
            }
            // `-d` and `-es` only after an e or a hissing sound.
            if end == "d" && !s.ends_with('e') || end == "es" && !(s.ends_with('s') || s.ends_with('x') || s.ends_with('z') || s.ends_with("ch") || s.ends_with("sh") || s.ends_with('o')) {
                continue;
            }
            if end == "s" && s.ends_with('s') {
                continue;
            }
            if let Some(p) = lex(&s) {
                return Some(match end {
                    "s" | "es" => add_s(p),
                    "ed" | "d" => add_ed(p),
                    _ => append(p, tail),
                });
            }
        }
    }
    // Prefixes on a known word.
    for (pre, head) in [
        ("un", &[P::Ah, P::N][..]),
        ("non", &[P::N, P::Aa, P::N][..]),
        ("re", &[P::R, P::Iy][..]),
        ("dis", &[P::D, P::Ih, P::S][..]),
        ("mis", &[P::M, P::Ih, P::S][..]),
        ("pre", &[P::P, P::R, P::Iy][..]),
        ("over", &[P::Ow, P::V, P::Er][..]),
        ("under", &[P::Ah, P::N, P::D, P::Er][..]),
        ("out", &[P::Aw, P::T][..]),
        ("up", &[P::Ah, P::P][..]),
        ("in", &[P::Ih, P::N][..]),
        ("im", &[P::Ih, P::M][..]),
        ("be", &[P::B, P::Ih][..]),
        ("inter", &[P::Ih, P::N, P::T, P::Er][..]),
        ("super", &[P::S, P::Uw, P::P, P::Er][..]),
        ("self", &[P::S, P::Eh, P::L, P::F][..]),
        ("anti", &[P::Ae, P::N, P::T, P::Iy][..]),
        ("sub", &[P::S, P::Ah, P::B][..]),
    ] {
        let Some(rest) = w.strip_suffix("").and_then(|w| w.strip_prefix(pre)) else { continue };
        if rest.len() < 3 {
            continue;
        }
        if let Some(p) = known(rest, lex, depth) {
            return Some(prepend(head, p));
        }
    }
    // Two known words.
    if n >= 6 {
        for k in (3..=n - 3).rev() {
            let (a, b) = (&w[..k], &w[k..]);
            if let (Some(pa), Some(pb)) = (lex(a), known(b, lex, depth)) {
                let mut p = pa;
                for (q, _) in pb {
                    if p.last().is_some_and(|&(r, _)| r == q && !matches!(q.manner(), crate::phoneme::Manner::Vowel | crate::phoneme::Manner::Diphthong)) {
                        continue;
                    }
                    p.push((q, false));
                }
                return Some(p);
            }
        }
    }
    None
}
